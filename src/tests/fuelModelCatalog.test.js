import { describe, it, expect } from 'vitest'
import { FuelModelCatalog, model, curableHerb } from '../index.js'

describe('FuelModelCatalog Class', () => {
    it('has FBFM13, FBFM40, and LANDFIRE fuel models available by number and code', () => {
        const catalog = new FuelModelCatalog()
        expect(catalog.has(1)).toBe(true)
        expect(catalog.has(101)).toBe(true)
        expect(catalog.has(99)).toBe(true)
    })
    it('keys are not case-sensitive', () => {
        const catalog = new FuelModelCatalog()
        expect(catalog.has('10')).toBe(true)
        expect(catalog.has('GR1')).toBe(true)
        expect(catalog.has('gr1')).toBe(true)
        expect(catalog.has('gR1')).toBe(true)
    })
    it('get() and has() return FALSE if key not found', () => {
        const catalog = new FuelModelCatalog()
        expect(catalog.has('junk')).toBe(false)
    })
    it('isCurable()', () => {
        const catalog = new FuelModelCatalog()
        expect(catalog.isCurable('gr1')).toBe(true)
        expect(catalog.isCurable('gr2')).toBe(true)
        expect(catalog.isCurable('gr3')).toBe(true)
        expect(catalog.isCurable('gr4')).toBe(true)
        expect(catalog.isCurable('gr5')).toBe(true)
        expect(catalog.isCurable('gr6')).toBe(true)
        expect(catalog.isCurable('gr7')).toBe(true)
        expect(catalog.isCurable('gr8')).toBe(true)
        expect(catalog.isCurable('gr9')).toBe(true)
        expect(catalog.isCurable('gs1')).toBe(true)
        expect(catalog.isCurable('gs2')).toBe(true)
        expect(catalog.isCurable('gs3')).toBe(true)
        expect(catalog.isCurable('gs4')).toBe(true)
        expect(catalog.isCurable('sh1')).toBe(true)
        expect(catalog.isCurable('sh9')).toBe(true)
        expect(catalog.isCurable('tu1')).toBe(true)
        expect(catalog.isCurable('tu3')).toBe(true)
        expect(catalog.isCurable(1)).toBe(false)
        expect(catalog.isCurable(2)).toBe(false)
        expect(catalog.isCurable(3)).toBe(false)
        expect(catalog.isCurable(4)).toBe(false)
        expect(catalog.isCurable(5)).toBe(false)
        expect(catalog.isCurable(6)).toBe(false)
        expect(catalog.isCurable(7)).toBe(false)
        expect(catalog.isCurable(8)).toBe(false)
        expect(catalog.isCurable(9)).toBe(false)
        expect(catalog.isCurable(10)).toBe(false)
        expect(catalog.isCurable(11)).toBe(false)
        expect(catalog.isCurable(12)).toBe(false)
        expect(catalog.isCurable(13)).toBe(false)
        expect(catalog.isCurable('tu2')).toBe(false)
        expect(catalog.isCurable('tu4')).toBe(false)
    })
    it('isBurnable()', () => {
        const catalog = new FuelModelCatalog()
        expect(catalog.isBurnable('1')).toBe(true)
        expect(catalog.isBurnable('gr1')).toBe(true)
        expect(catalog.isBurnable(91)).toBe(false)
        expect(catalog.isBurnable(92)).toBe(false)
        expect(catalog.isBurnable(93)).toBe(false)
        expect(catalog.isBurnable(98)).toBe(false)
        expect(catalog.isBurnable(99)).toBe(false)
        expect(catalog.isBurnable('nb1')).toBe(false)
        expect(catalog.isBurnable('nb2')).toBe(false)
        expect(catalog.isBurnable('nb3')).toBe(false)
        expect(catalog.isBurnable('nb8')).toBe(false)
        expect(catalog.isBurnable('nb9')).toBe(false)
    })
    it('getCuringClasses()', () => {
        const catalog = new FuelModelCatalog()
        const keys = catalog.getStringKeys()
        const curingClasses = catalog.getCuringClasses(keys)
        expect(curingClasses).toContain('curedHerb')
    })
    it('getMoistureClasses()', () => {
        const catalog = new FuelModelCatalog()
        const keys = catalog.getStringKeys()
        const moistureClasses = catalog.getMoistureClasses(keys)
        console.log(moistureClasses)
        expect(moistureClasses).toContain('moistureDead1h')
        expect(moistureClasses).toContain('moistureDead10h')
        expect(moistureClasses).toContain('moistureDead100h')
        expect(moistureClasses).toContain('moistureLiveStem')
        expect(moistureClasses).toContain('moistureLiveHerb')
    })

    it('set() custom fuel model', () => {
        const catalog = new FuelModelCatalog()
        expect(catalog.has('cheatgrass')).toBe(false)
        
        const Cheatgrass = model(301, "Cheatgrass", "Bevins 2026", "Curable Cheatgrass",
            "Curable Cheatgrass as an example custom model",
            1, 0.15, [curableHerb(0.0872359963269054, 1800, 8000)])
        catalog.set(Cheatgrass)

        expect(catalog.has('cheatgrass')).toBe(true)
        expect(catalog.isBurnable('cheatgrass')).toBe(true)
        expect(catalog.isCurable('cheatgrass')).toBe(true)
    })
})
